#ifndef FRACTAL_OPENCL_KERNEL_H
#define FRACTAL_OPENCL_KERNEL_H

static const char fractal_opencl_kernel[] =
    "#ifdef USE_AMD_FP64\n"
    "#pragma OPENCL EXTENSION cl_amd_fp64 : enable\n"
    "#else\n"
    "#pragma OPENCL EXTENSION cl_khr_fp64 : enable\n"
    "#endif\n"
    "__kernel void render_fractal(__global uchar4 *pixels, uint width, uint height, uint max_iter, uint kind,\n"
    "    double x_min, double x_max, double y_min, double y_max, double julia_re, double julia_im,\n"
    "    double escape_radius, uint color_mode, double red_a, double red_b, double blue_a, double blue_b,\n"
    "    ulong val_in, ulong val_out, uint attenuation,\n"
    "    uchar ir, uchar ig, uchar ib, uchar sr, uchar sg, uchar sb, uchar er, uchar eg, uchar eb)\n"
    "{\n"
    "    size_t index = get_global_id(0);\n"
    "    size_t count = (size_t)width * (size_t)height;\n"
    "    if (index >= count) return;\n"
    "    uint x = (uint)(index % width), y = (uint)(index / width);\n"
    "    double x_span = x_max - x_min, y_span = y_max - y_min;\n"
    "    double point_re = x_min + x_span * (double)x / (double)(width > 1 ? width - 1 : 1);\n"
    "    double point_im = y_max - y_span * (double)y / (double)(height > 1 ? height - 1 : 1);\n"
    "    double zr = kind == 1 ? point_re : 0.0;\n"
    "    double zi = kind == 1 ? point_im : 0.0;\n"
    "    double cr = kind == 1 ? julia_re : point_re;\n"
    "    double ci = kind == 1 ? julia_im : point_im;\n"
    "    double mag2 = 0.0; uint iter = 0;\n"
    "    while (iter < max_iter && mag2 < escape_radius) {\n"
    "        double next_r = zr * zr - zi * zi + cr;\n"
    "        zi = 2.0 * zr * zi + ci; zr = next_r; mag2 = zr * zr + zi * zi; ++iter;\n"
    "    }\n"
    "    uchar r = ir, g = ig, b = ib;\n"
    "    if (color_mode == 1) {\n"
    "        double rv = red_a + (red_b - red_a) * (double)x / (double)width;\n"
    "        double bv = blue_a + (blue_b - blue_a) * (double)y / (double)height;\n"
    "        double gv = 0.0;\n"
    "        if ((ulong)iter >= val_in) gv = 255.0 - (((double)iter + (double)val_in) / ((double)max_iter + (double)val_in)) * (255.0 - (double)val_out);\n"
    "        double atten = 1.0;\n"
    "        if (attenuation != 0) { double f = (double)iter / (double)max_iter; atten = 1.0 - f * f; }\n"
    "        r = convert_uchar_sat_rtz(clamp(rv * atten, 0.0, 255.0));\n"
    "        g = convert_uchar_sat_rtz(clamp(gv, 0.0, 255.0));\n"
    "        b = convert_uchar_sat_rtz(clamp(bv * atten, 0.0, 255.0));\n"
    "    } else if (mag2 >= escape_radius) {\n"
    "        double smooth_iter = (double)iter;\n"
    "        if (isfinite(mag2) && mag2 > 1.0) {\n"
    "            double log_mag = 0.5 * log(mag2);\n"
    "            if (log_mag > 0.0) {\n"
    "                double correction = log(log_mag / log(2.0)) / log(2.0);\n"
    "                if (isfinite(correction)) smooth_iter += 1.0 - correction;\n"
    "            }\n"
    "        }\n"
    "        double t = clamp(smooth_iter / (double)max_iter, 0.0, 1.0);\n"
    "        r = convert_uchar_sat_rtz((double)sr + ((double)er - (double)sr) * t);\n"
    "        g = convert_uchar_sat_rtz((double)sg + ((double)eg - (double)sg) * t);\n"
    "        b = convert_uchar_sat_rtz((double)sb + ((double)eb - (double)sb) * t);\n"
    "    }\n"
    "    pixels[index] = (uchar4)(r, g, b, 255);\n"
    "}\n";

#endif
